begin
  perform pg_advisory_xact_lock(7281,1);
  for x in select r.event_id from rally.rsvps r join rally.events e on e.id=r.event_id
    where r.user_id=p_uid and r.status in ('going','waiting','payment_pending') and not e.deleted
      and ((e.date+e.start_time) at time zone 'Asia/Seoul')>now() order by r.event_id loop
