create or replace function rally.dues_exemption(u rally.users,p_month text) returns text language plpgsql stable set search_path='' as $$
declare first_day date := (p_month || '-01')::date; last_day date := (first_day+interval '1 month - 1 day')::date; joined date := coalesce(u.somoim_joined,(u.created_at at time zone 'Asia/Seoul')::date);
begin
  if u.is_admin then return '운영진'; end if;
  if joined between last_day-10 and last_day then return '월말 가입 (말일−10일부터)'; end if;
  if exists(select 1 from rally.annual_passes where user_id=u.id and not revoked and p_month between start_month and end_month) then return '기존 1년권'; end if;
  if (select count(*) from rally.events where host_id=u.id and not deleted and date between first_day and last_day
    and ((date+end_time) at time zone 'Asia/Seoul')<=now())>=3 then return '해당 월 호스트 3회'; end if;
  return null;
end $$;
create or replace function rally.dues_required(u rally.users,p_month text) returns boolean language sql stable set search_path='' as $$
