-- Existing installations: run this file once in Supabase SQL Editor.
-- No payments are transferred by this migration. Existing future paid-event
-- attendance without a receipt is moved to payment_pending for verification.
begin;
set local check_function_bodies = off;

alter table rally.users add column if not exists station_confirmed boolean not null default false;
alter table rally.rsvps drop constraint if exists rsvps_status_check;
alter table rally.rsvps add constraint rsvps_status_check check (status in ('going','waiting','payment_pending','declined'));

create table if not exists rally.event_payments (
  event_id bigint references rally.events(id), user_id bigint references rally.users(id),
  amount integer not null check (amount >= 0),
  status text not null default 'pending' check (status in ('pending','reported','paid','refund_pending','refunded','void')),
  payer_name text, reference text, confirmed_by bigint references rally.users(id), confirmed_at timestamptz,
  updated_at timestamptz not null default now(), primary key(event_id,user_id)
);
create table if not exists rally.penalties (
  id bigint generated by default as identity primary key,
  event_id bigint not null references rally.events(id), user_id bigint not null references rally.users(id),
  kind text not null check (kind in ('cancellation','late15','late30','no_show')),
  amount integer not null check (amount >= 0), review_allowed boolean not null default false,
  blocks_attendance boolean not null default false,
  status text not null default 'unpaid' check (status in ('unpaid','reported','settled','waived')),
  note text not null default '', evidence text, resolution text,
  recorded_by bigint references rally.users(id), resolved_by bigint references rally.users(id),
  created_at timestamptz not null default now(), resolved_at timestamptz
);
create unique index if not exists penalties_attendance_once on rally.penalties(event_id,user_id) where kind <> 'cancellation';
create table if not exists rally.cancellations (
  id bigint generated by default as identity primary key, event_id bigint references rally.events(id), user_id bigint references rally.users(id),
  reason text not null, penalty_id bigint references rally.penalties(id), replacement_id bigint references rally.users(id),
  replacement_status text not null default 'needed' check (replacement_status in ('needed','confirmed','not_required')),
  created_at timestamptz not null default now()
);
create table if not exists rally.inbox (
  id bigint generated by default as identity primary key, user_id bigint not null references rally.users(id),
  event_id bigint references rally.events(id), title text not null, body text not null,
  read_at timestamptz, created_at timestamptz not null default now()
);
create index if not exists inbox_user_created on rally.inbox(user_id,created_at desc);
create table if not exists rally.ntrp_requests (
  id bigint generated by default as identity primary key, user_id bigint not null references rally.users(id),
  requested numeric(2,1) not null, reason text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  resolved_by bigint references rally.users(id), created_at timestamptz not null default now()
);
create unique index if not exists ntrp_one_pending on rally.ntrp_requests(user_id) where status='pending';
create table if not exists rally.annual_passes (
  id bigint generated by default as identity primary key, user_id bigint not null references rally.users(id),
  start_month text not null, end_month text not null, note text not null,
  created_by bigint not null references rally.users(id), revoked boolean not null default false,
  check (start_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$' and end_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$' and start_month <= end_month)
);
create table if not exists rally.event_reviews (
  event_id bigint primary key references rally.events(id), host_id bigint not null references rally.users(id),
  body text not null check (length(body) between 1 and 3000),
  participant_ids bigint[] not null, updated_at timestamptz not null default now()
);
create table if not exists rally.payment_audit (
  id bigint generated by default as identity primary key, event_id bigint references rally.events(id), user_id bigint references rally.users(id),
  actor_id bigint references rally.users(id), action text not null, note text not null, created_at timestamptz not null default now()
);

create or replace function rally.event_fee(e rally.events) returns integer language sql immutable set search_path='' as $$
  select (ceil((e.court_fee + e.ball_fee)::numeric / greatest(e.capacity,1) / 100) * 100)::integer
$$;
create or replace function rally.attendance_blocked(p_uid bigint) returns boolean language sql stable set search_path='' as $$
  select exists(select 1 from rally.penalties where user_id=p_uid and blocks_attendance and status in ('unpaid','reported'))
$$;
create or replace function rally.eligible(e rally.events,u rally.users) returns boolean language sql stable set search_path='' as $$
  select u.banned_at is null and not rally.attendance_blocked(u.id)
    and (e.game_type <> 'mens' or u.gender='M') and (e.game_type <> 'womens' or u.gender='F')
    and (e.ntrp_min is null or u.ntrp >= e.ntrp_min) and (e.ntrp_max is null or u.ntrp <= e.ntrp_max)
$$;
create or replace function rally.has_seat(e rally.events,u rally.users) returns boolean language sql stable set search_path='' as $$
  select (select count(*) from rally.rsvps r join rally.users x on x.id=r.user_id
    where r.event_id=e.id and r.status='going' and r.user_id<>u.id and (e.game_type<>'mixed' or x.gender=u.gender))
    < case when e.game_type='mixed' then case when u.gender='M' then e.male_cap else e.female_cap end else e.capacity end
$$;
create or replace function rally.notify_event(p_eid bigint,p_uid bigint,p_title text,p_body text) returns void language sql set search_path='' as $$
  insert into rally.inbox(user_id,event_id,title,body)
  select id,p_eid,p_title,p_body from rally.users
  where banned_at is null and (id=p_uid or is_admin or id=(select host_id from rally.events where id=p_eid))
$$;
create or replace function rally.manage_event(p_token text,p_eid bigint) returns rally.users language plpgsql stable set search_path='' as $$
declare u rally.users := rally.require_user(p_token); e rally.events;
begin
  select * into e from rally.events where id=p_eid and not deleted;
  if e.id is null then raise exception '일정을 찾을 수 없어요.'; end if;
  if e.host_id<>u.id and not u.is_admin then raise exception '해당 호스트와 운영진만 관리할 수 있어요.'; end if;
  return u;
end $$;

-- Promotion rechecks eligibility and never confirms unpaid participation.
create or replace function rally.promote(p_eid bigint) returns void language plpgsql set search_path='' as $$
declare e rally.events; u rally.users; next_status text;
begin
  select * into e from rally.events where id=p_eid and not deleted for update;
  if e.id is null or ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then return; end if;
  for u in select x.* from rally.rsvps r join rally.users x on x.id=r.user_id
    where r.event_id=p_eid and r.status='waiting' order by r.queued_at loop
    if not rally.eligible(e,u) or not rally.has_seat(e,u) then continue; end if;
    next_status := case when rally.event_fee(e)=0 or exists(select 1 from rally.event_payments p
      where p.event_id=p_eid and p.user_id=u.id and p.status='paid') then 'going' else 'payment_pending' end;
    update rally.rsvps set status=next_status where event_id=p_eid and user_id=u.id;
    if next_status='going' then insert into rally.promotions(event_id,user_id) values(p_eid,u.id); end if;
    perform rally.notify_event(p_eid,u.id,case when next_status='going' then '참석 확정' else '입금 확인 대기' end,
      e.title || case when next_status='going' then ' · 자리가 배정됐어요.' else ' · 입금 전 호스트에게 자리와 금액을 확인해주세요. 입금 대기는 자리 확정이 아니에요.' end);
  end loop;
end $$;

