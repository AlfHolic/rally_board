    update rally.rsvps set status='declined' where event_id=x.event_id and user_id=p_uid;
    update rally.event_payments set status=case when status='paid' then 'refund_pending' else 'void' end,updated_at=now()
      where event_id=x.event_id and user_id=p_uid and status in ('paid','pending','reported');
    perform rally.notify_event(x.event_id,p_uid,'탈퇴 회원 신청 취소','회원 탈퇴로 신청이 취소됐어요. 참가비 환불 대기 내역을 확인해주세요.');
