    update rally.rsvps set status='declined' where event_id=new.id;
  elsif not new.deleted and (new.date,new.start_time,new.end_time,new.court) is distinct from (old.date,old.start_time,old.end_time,old.court) then
    for x in select user_id from rally.rsvps where event_id=new.id and status in ('going','waiting','payment_pending') loop
