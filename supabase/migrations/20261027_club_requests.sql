create or replace function public.rb_claim_club_pushes(p_secret text) returns jsonb language plpgsql security definer set search_path='' as $$
declare result jsonb;
begin
  perform rally.check_secret(p_secret);
  with claimed as (
    update rally.inbox set push_claimed_until=now()+interval '5 minutes',push_attempts=push_attempts+1
    where id in (select n.id from rally.inbox n where n.push_sent_at is null and n.push_next_at<=now()
      and (n.push_claimed_until is null or n.push_claimed_until<=now())
      and exists(select 1 from rally.push_subs s join rally.users u on u.id=s.user_id where s.user_id=n.user_id and u.banned_at is null)
      order by n.id limit 50 for update skip locked)
    returning *
  ) select coalesce(jsonb_agg(jsonb_build_object('id',id,'title',title,'body',body,'url','/?tab=mine','subs',rally.subs_json(array[user_id]))),'[]'::jsonb) into result from claimed;
  return result;
end $$;
create or replace function public.rb_finish_club_push(p_secret text,p_id bigint,p_ok boolean) returns void language plpgsql security definer set search_path='' as $$
begin
  perform rally.check_secret(p_secret);
  update rally.inbox set push_sent_at=case when p_ok then now() else null end,push_claimed_until=null,
    push_next_at=now()+make_interval(secs=>least(3600,60*power(2,least(push_attempts,6)))::double precision)
    where id=p_id and push_sent_at is null;
end $$;

