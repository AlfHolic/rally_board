begin
  perform pg_advisory_xact_lock(7281,1);
  select * into p from rally.penalties where id=p_id for update;
  if p.id is null or p.status not in ('unpaid','reported') then raise exception '처리할 벌칙이 없어요.'; end if;
  if u.id=p.user_id then raise exception '본인 벌칙은 다른 운영진에게 확인을 요청해주세요.'; end if;
  if p_resolution not in ('paid','review','waived') or length(btrim(coalesce(p_note,''))) not between 1 and 300 then raise exception '처리 방식과 확인 근거를 적어주세요.'; end if;
  if p_resolution='review' and not p.review_allowed then raise exception '이 벌칙은 당근리뷰로 대체할 수 없어요.'; end if;
  update rally.penalties set status=case when p_resolution='waived' then 'waived' else 'settled' end,
    resolution=p_resolution || ': ' || p_note,resolved_by=u.id,resolved_at=now() where id=p_id;
  perform rally.notify_event(p.event_id,p.user_id,'벌칙 처리 완료','확인이 완료됐어요. 미납 지각·불참 벌칙이 모두 해소되면 다시 신청할 수 있어요. 취소된 정모는 자동 복구되지 않아요.');
