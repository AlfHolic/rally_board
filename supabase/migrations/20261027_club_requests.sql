create or replace function public.rb_set_station(p_token text,p_station text) returns void language plpgsql security definer set search_path='' as $$
declare u rally.users := rally.require_user(p_token); s text := btrim(coalesce(p_station,''));
begin
  if length(s)<2 or length(s)>12 or s !~ '역$' or position('/' in s)>0 then raise exception '지하철역 이름을 역까지 적어주세요. 예: 삼전역'; end if;
  update rally.users set region=s,station_confirmed=true,nickname=rally.make_nick(name,birth_yy,s,gender,ntrp,freq) where id=u.id;
end $$;

-- Applies equally to existing and new clients; an unpaid join is never going.
create or replace function public.rb_respond(p_token text,p_id bigint,p_action text) returns text language plpgsql security definer set search_path='' as $$
declare u rally.users := rally.require_user(p_token); e rally.events; cur text; target text; pay rally.event_payments;
begin
  perform pg_advisory_xact_lock(7281,1);
  select * into e from rally.events where id=p_id and not deleted for update;
  if e.id is null then raise exception '일정을 찾을 수 없어요.'; end if;
  if p_action='decline' then return public.rb_cancel_registration(p_token,p_id,'본인 취소'); end if;
  if p_action<>'join' then raise exception '알 수 없는 요청이에요.'; end if;
  if ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then raise exception '이미 시작된 일정이에요.'; end if;
  if rally.attendance_blocked(u.id) then raise exception '미납 지각·불참 벌칙이 있어 참석할 수 없어요. 내 정모에서 확인해주세요.'; end if;
  if not rally.eligible(e,u) then raise exception '성별 또는 NTRP 참가 조건에 맞지 않아요.'; end if;
  select status into cur from rally.rsvps where event_id=p_id and user_id=u.id;
  if cur in ('going','waiting','payment_pending') then return cur; end if;
  select * into pay from rally.event_payments where event_id=p_id and user_id=u.id;
  if pay.status='refund_pending' then raise exception '이전 신청의 환불 확인이 필요해요. 호스트에게 문의해주세요.'; end if;
  if rally.event_fee(e)>0 then
    insert into rally.event_payments(event_id,user_id,amount) values(p_id,u.id,rally.event_fee(e))
      on conflict(event_id,user_id) do update set status='pending',amount=excluded.amount,payer_name=null,reference=null,confirmed_by=null,confirmed_at=null,updated_at=now();
  end if;
  target := case when not rally.has_seat(e,u) then 'waiting' when rally.event_fee(e)>0 then 'payment_pending' else 'going' end;
  insert into rally.rsvps(event_id,user_id,status) values(p_id,u.id,target)
    on conflict(event_id,user_id) do update set status=excluded.status,queued_at=clock_timestamp(),attended=null;
  return target;
end $$;

create or replace function public.rb_report_event_payment(p_token text,p_event_id bigint,p_payer text) returns void language plpgsql security definer set search_path='' as $$
declare u rally.users := rally.require_user(p_token); e rally.events;
begin
  perform pg_advisory_xact_lock(7281,1);
  select * into e from rally.events where id=p_event_id and not deleted;
  if e.id is null or ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then raise exception '입금 확인을 요청할 수 없는 일정이에요.'; end if;
  if length(btrim(coalesce(p_payer,''))) not between 1 and 30 then raise exception '입금자명을 1~30자로 적어주세요.'; end if;
  if not exists(select 1 from rally.rsvps where event_id=p_event_id and user_id=u.id and status='payment_pending') then raise exception '입금 대기 상태에서만 확인 요청할 수 있어요. 자리 대기 중에는 입금하지 마세요.'; end if;
  update rally.event_payments set status='reported',payer_name=btrim(p_payer),updated_at=now()
    where event_id=p_event_id and user_id=u.id and status in ('pending','reported');
  if not found then raise exception '입금 대기 내역이 없어요.'; end if;
  perform rally.notify_event(p_event_id,u.id,'참가비 확인 요청',u.nickname || ' · 실제 입금 내역을 확인해주세요.');
end $$;

create or replace function public.rb_confirm_event_payment(p_token text,p_event_id bigint,p_uid bigint,p_reference text) returns text language plpgsql security definer set search_path='' as $$
declare actor rally.users; u rally.users; e rally.events; p rally.event_payments; target text;
begin
  perform pg_advisory_xact_lock(7281,1);
  actor := rally.manage_event(p_token,p_event_id);
  if actor.id=p_uid then raise exception '본인 입금은 다른 운영진에게 확인을 요청해주세요.'; end if;
  if length(btrim(coalesce(p_reference,''))) not between 1 and 200 then raise exception '실제 입금 확인 근거를 적어주세요. 예: 입금일시·입금자명'; end if;
  select * into e from rally.events where id=p_event_id for update;
  select * into u from rally.users where id=p_uid;
  select * into p from rally.event_payments where event_id=p_event_id and user_id=p_uid for update;
  if p.status='paid' then return (select status from rally.rsvps where event_id=p_event_id and user_id=p_uid); end if;
  if p.event_id is null or p.status not in ('pending','reported') then raise exception '확인할 입금 대기 내역이 없어요.'; end if;
  if not exists(select 1 from rally.rsvps where event_id=p_event_id and user_id=p_uid and status in ('waiting','payment_pending')) then raise exception '취소된 신청이에요.'; end if;
  if ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then raise exception '시작된 일정의 입금 처리는 운영진에게 문의해주세요.'; end if;
  if not rally.eligible(e,u) then raise exception '참가 제한 또는 참가 조건을 먼저 확인해주세요.'; end if;
  update rally.event_payments set status='paid',reference=btrim(p_reference),confirmed_by=actor.id,confirmed_at=now(),updated_at=now() where event_id=p_event_id and user_id=p_uid;
  target := case when rally.has_seat(e,u) then 'going' else 'waiting' end;
  update rally.rsvps set status=target where event_id=p_event_id and user_id=p_uid;
  insert into rally.payment_audit(event_id,user_id,actor_id,action,note) values(p_event_id,p_uid,actor.id,'payment_confirmed',p_reference);
  perform rally.notify_event(p_event_id,p_uid,'참가비 입금 확인',e.title || case when target='going' then ' · 참석이 확정됐어요.' else ' · 정원이 차서 자리 대기 중이에요. 호스트와 참가 또는 환불을 확인해주세요.' end);
  return target;
end $$;

create or replace function public.rb_manage_participant(p_token text,p_event_id bigint,p_uid bigint,p_status text) returns void language plpgsql security definer set search_path='' as $$
declare actor rally.users; u rally.users; e rally.events;
begin
  perform pg_advisory_xact_lock(7281,1);
  actor := rally.manage_event(p_token,p_event_id);
  select * into e from rally.events where id=p_event_id for update;
  select * into u from rally.users where id=p_uid;
  if ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then raise exception '시작된 일정은 참석 상태를 바꿀 수 없어요.'; end if;
  if p_status not in ('going','waiting','payment_pending') then raise exception '참석 상태를 확인해주세요.'; end if;
  if not rally.eligible(e,u) then raise exception '참가 제한 또는 참가 조건에 맞지 않아요.'; end if;
  if p_status='going' then
    if rally.event_fee(e)>0 and not exists(select 1 from rally.event_payments where event_id=p_event_id and user_id=p_uid and status='paid') then raise exception '실제 입금 확인 전에는 참석 확정할 수 없어요.'; end if;
    if not rally.has_seat(e,u) then raise exception '정원이 찼어요.'; end if;
  end if;
  update rally.rsvps set status=p_status where event_id=p_event_id and user_id=p_uid and status<>'declined';
  if not found then raise exception '유효한 참가 신청이 없어요.'; end if;
  perform rally.notify_event(p_event_id,p_uid,'참가 상태 변경',e.title || ' · 호스트 또는 운영진이 참가 상태를 변경했어요.');
end $$;

create or replace function public.rb_cancel_quote(p_token text,p_event_id bigint) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare u rally.users := rally.require_user(p_token); e rally.events; d integer; a integer := 0; cur text;
begin
  select * into e from rally.events where id=p_event_id and not deleted;
  if e.id is null then raise exception '일정을 찾을 수 없어요.'; end if;
  select status into cur from rally.rsvps where event_id=p_event_id and user_id=u.id;
  d := e.date - (now() at time zone 'Asia/Seoul')::date;
  if cur='going' then a := case when d>=4 then 0 when d>=2 then 2000 when d=1 then 5000 else 10000 end; end if;
  return jsonb_build_object('amount',a,'reviewAllowed',cur='going' and d=0,'replacementRequired',cur='going',
    'refundPending',exists(select 1 from rally.event_payments where event_id=p_event_id and user_id=u.id and status='paid'));
end $$;

create or replace function public.rb_cancel_registration(p_token text,p_event_id bigint,p_reason text) returns text language plpgsql security definer set search_path='' as $$
declare u rally.users := rally.require_user(p_token); e rally.events; cur text; q jsonb; pen bigint;
begin
  perform pg_advisory_xact_lock(7281,1);
  select * into e from rally.events where id=p_event_id and not deleted for update;
  if e.id is null then raise exception '일정을 찾을 수 없어요.'; end if;
  if ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then raise exception '시작된 일정은 호스트에게 지각·불참 처리를 요청해주세요.'; end if;
  select status into cur from rally.rsvps where event_id=p_event_id and user_id=u.id;
  if cur is null or cur='declined' then return 'declined'; end if;
  if length(btrim(coalesce(p_reason,''))) not between 1 and 200 then raise exception '취소 사유를 1~200자로 적어주세요.'; end if;
  q := public.rb_cancel_quote(p_token,p_event_id);
  if (q->>'amount')::int>0 then
    insert into rally.penalties(event_id,user_id,kind,amount,review_allowed,note,recorded_by)
      values(p_event_id,u.id,'cancellation',(q->>'amount')::int,(q->>'reviewAllowed')::boolean,p_reason,u.id) returning id into pen;
  end if;
  insert into rally.cancellations(event_id,user_id,reason,penalty_id,replacement_status)
    values(p_event_id,u.id,p_reason,pen,case when cur='going' then 'needed' else 'not_required' end);
  update rally.rsvps set status='declined' where event_id=p_event_id and user_id=u.id;
  update rally.event_payments set status=case when status='paid' then 'refund_pending' else 'void' end,updated_at=now()
    where event_id=p_event_id and user_id=u.id and status in ('paid','pending','reported');
  perform rally.notify_event(p_event_id,u.id,'정모 참가 취소',u.nickname || ' · ' || e.title || ' · ' || p_reason || ' · 환불 및 대참 정산은 호스트와 확인해주세요.');
  perform rally.promote(p_event_id);
  return 'declined';
end $$;

create or replace function public.rb_record_attendance_penalty(p_token text,p_event_id bigint,p_uid bigint,p_kind text,p_note text) returns bigint language plpgsql security definer set search_path='' as $$
declare actor rally.users; e rally.events; x record; pen bigint; a integer;
begin
  perform pg_advisory_xact_lock(7281,1);
  actor := rally.manage_event(p_token,p_event_id);
  select * into e from rally.events where id=p_event_id;
  if ((e.date+e.start_time) at time zone 'Asia/Seoul')>now() then raise exception '정모 시작 후 기록할 수 있어요.'; end if;
  if p_kind not in ('late15','late30','no_show') then raise exception '지각·불참 종류를 확인해주세요.'; end if;
  if not exists(select 1 from rally.rsvps where event_id=p_event_id and user_id=p_uid and status='going') then raise exception '참석 확정된 멤버만 기록할 수 있어요.'; end if;
  if length(btrim(coalesce(p_note,''))) not between 1 and 200 then raise exception '확인한 지각·불참 내용을 적어주세요.'; end if;
  if exists(select 1 from rally.penalties where event_id=p_event_id and user_id=p_uid and kind<>'cancellation') then raise exception '이미 지각·불참 기록이 있어요. 운영진에게 정정을 요청해주세요.'; end if;
  a := case p_kind when 'late15' then 5000 when 'late30' then 10000 else 15000 end;
  insert into rally.penalties(event_id,user_id,kind,amount,review_allowed,blocks_attendance,note,recorded_by)
    values(p_event_id,p_uid,p_kind,a,p_kind='no_show',true,p_note,actor.id) returning id into pen;
  update rally.rsvps set attended=(p_kind<>'no_show') where event_id=p_event_id and user_id=p_uid;
  for x in select r.event_id,ev.title from rally.rsvps r join rally.events ev on ev.id=r.event_id
    where r.user_id=p_uid and r.status in ('going','waiting','payment_pending') and not ev.deleted
      and ((ev.date+ev.start_time) at time zone 'Asia/Seoul')>now() order by r.event_id loop
    perform 1 from rally.events where id=x.event_id for update;
    update rally.rsvps set status='declined' where event_id=x.event_id and user_id=p_uid;
    update rally.event_payments set status=case when status='paid' then 'refund_pending' else 'void' end,updated_at=now()
      where event_id=x.event_id and user_id=p_uid and status in ('paid','pending','reported');
    insert into rally.cancellations(event_id,user_id,reason,replacement_status) values(x.event_id,p_uid,'지각·불참 벌칙 미납으로 자동 취소','not_required');
