-- Prevent overbooking or retroactively invalidating accepted registrations.
create or replace function rally.guard_event_changes() returns trigger language plpgsql set search_path='' as $$
begin
  if new.deleted then return new; end if;
  if (new.capacity,new.male_cap,new.female_cap,new.game_type,new.ntrp_min,new.ntrp_max,new.court_fee,new.ball_fee)
     is distinct from (old.capacity,old.male_cap,old.female_cap,old.game_type,old.ntrp_min,old.ntrp_max,old.court_fee,old.ball_fee) then
    if (select count(*) from rally.rsvps where event_id=new.id and status='going')>new.capacity then raise exception '확정 인원보다 정원을 줄일 수 없어요.'; end if;
    if exists(select 1 from rally.rsvps r join rally.users u on u.id=r.user_id where r.event_id=new.id and r.status='going'
      and ((new.game_type='mens' and u.gender<>'M') or (new.game_type='womens' and u.gender<>'F') or (new.ntrp_min is not null and u.ntrp<new.ntrp_min) or (new.ntrp_max is not null and u.ntrp>new.ntrp_max))) then raise exception '기존 참석자가 변경한 참가 조건에 맞지 않아요. 먼저 참가 상태를 확인해주세요.'; end if;
    if new.game_type='mixed' and ((select count(*) from rally.rsvps r join rally.users u on u.id=r.user_id where r.event_id=new.id and r.status='going' and u.gender='M')>new.male_cap or (select count(*) from rally.rsvps r join rally.users u on u.id=r.user_id where r.event_id=new.id and r.status='going' and u.gender='F')>new.female_cap) then raise exception '확정 인원보다 성별 정원을 줄일 수 없어요.'; end if;
    if rally.event_fee(new)<>rally.event_fee(old) and exists(select 1 from rally.event_payments where event_id=new.id and status in ('pending','reported','paid','refund_pending')) then raise exception '입금 내역이 있는 일정의 1인 참가비는 변경할 수 없어요. 먼저 신청·환불 내역을 정리해주세요.'; end if;
  end if;
  return new;
end $$;
drop trigger if exists guard_event_changes on rally.events;
create trigger guard_event_changes before update on rally.events for each row execute function rally.guard_event_changes();

