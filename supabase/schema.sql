CREATE OR REPLACE FUNCTION public.rb_ranking(p_period text, p_kind text DEFAULT 'host'::text)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  with m as (select to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM') as month),
  src as (
    select e.host_id as uid, e.date from rally.events e where p_kind <> 'attend' and not e.deleted
    union all
    select r.user_id as uid, e.date
    from rally.rsvps r join rally.events e on e.id = r.event_id
    where p_kind = 'attend' and not e.deleted and r.status = 'going' and r.attended is not false
      and ((e.date + e.start_time) at time zone 'Asia/Seoul') <= now()
  ),
  c as (
    select u.id, u.nickname, u.gender, u.ntrp, count(*)::int as n, max(s.date) as last
    from src s join rally.users u on u.id = s.uid
    where u.banned_at is null and (p_period <> 'month' or to_char(s.date, 'YYYY-MM') = (select month from m))
    group by u.id
  )
  select jsonb_build_object(
    'month', (select month from m),
    'members', (select count(*) from rally.users where banned_at is null),
    'list', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nickname', nickname, 'gender', gender, 'ntrp', ntrp, 'n', n,
