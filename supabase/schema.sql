CREATE OR REPLACE FUNCTION public.rb_respond(p_token text, p_id bigint, p_action text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  u rally.users := rally.require_user(p_token);
  ev rally.events; v_mine text; v_going int; v_cap int; v_status text;
begin
  select * into ev from rally.events where id = p_id and not deleted for update;
  if ev.id is null then raise exception '일정을 찾을 수 없어요.'; end if;
  if ((ev.date + ev.end_time) at time zone 'Asia/Seoul') < now() then raise exception '이미 끝난 일정이에요.'; end if;
  select status into v_mine from rally.rsvps where event_id = p_id and user_id = u.id;

  if p_action = 'join' then
    if ev.game_type = 'mens' and u.gender <> 'M' then raise exception '남복 일정이에요.'; end if;
    if ev.game_type = 'womens' and u.gender <> 'F' then raise exception '여복 일정이에요.'; end if;
    if ev.ntrp_min is not null and u.ntrp < ev.ntrp_min then raise exception 'NTRP % 이상만 참석할 수 있어요.', ev.ntrp_min; end if;
    if ev.ntrp_max is not null and u.ntrp > ev.ntrp_max then raise exception 'NTRP % 이하만 참석할 수 있어요.', ev.ntrp_max; end if;
    if v_mine in ('going','waiting') then return v_mine; end if;
    v_cap := case when ev.game_type = 'mixed' then (case when u.gender = 'M' then ev.male_cap else ev.female_cap end) else ev.capacity end;
    select count(*) into v_going from rally.rsvps r join rally.users x on x.id = r.user_id
      where r.event_id = p_id and r.status = 'going' and (ev.game_type <> 'mixed' or x.gender = u.gender);
    v_status := case when v_going < v_cap then 'going' else 'waiting' end;
    insert into rally.rsvps(event_id, user_id, status, queued_at) values (p_id, u.id, v_status, clock_timestamp())
      on conflict (event_id, user_id) do update set status = excluded.status, queued_at = excluded.queued_at;
    return v_status;
  elsif p_action = 'decline' then
    if v_mine = 'going' and ev.cancel_hours > 0
       and now() > ((ev.date + ev.start_time) at time zone 'Asia/Seoul') - make_interval(hours => ev.cancel_hours) then
      raise exception '시작 %시간 전부터는 취소할 수 없어요. 방장에게 말해주세요.', ev.cancel_hours;
    end if;
    insert into rally.rsvps(event_id, user_id, status, queued_at) values (p_id, u.id, 'declined', clock_timestamp())
      on conflict (event_id, user_id) do update set status = 'declined', queued_at = excluded.queued_at;
    if v_mine = 'going' then perform rally.promote(p_id); end if;
    return 'declined';
  end if;
  raise exception '알 수 없는 요청이에요.';
end $function$
;

