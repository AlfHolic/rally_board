      select jsonb_agg(jsonb_build_object('id', c.id, 'userId', c.user_id, 'nickname', rally.shown_name(u), 'body', c.body,
        'createdAt', to_char(c.created_at at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI')) order by c.created_at)
      from rally.comments c join rally.users u on u.id = c.user_id where c.event_id = e.id and not c.deleted), '[]'::jsonb))
$function$
;

