-- Older attendance controls must not bypass no-show penalties/restrictions.
create or replace function public.rb_set_attendance(p_token text,p_event_id bigint,p_uid bigint,p_attended boolean) returns void language plpgsql security definer set search_path='' as $$
declare actor rally.users; e rally.events;
begin
  perform pg_advisory_xact_lock(7281,1);
  actor := rally.manage_event(p_token,p_event_id);
  select * into e from rally.events where id=p_event_id;
  if ((e.date+e.start_time) at time zone 'Asia/Seoul')>now() then raise exception '정모 시작 후 기록할 수 있어요.'; end if;
  if p_attended is false then
    perform public.rb_record_attendance_penalty(p_token,p_event_id,p_uid,'no_show','호스트·운영진 출석 체크에서 무단 불참 확인');
    return;
  end if;
  if exists(select 1 from rally.penalties where event_id=p_event_id and user_id=p_uid and kind='no_show' and status<>'waived') then
    raise exception '무단 불참 기록을 되돌리려면 운영진이 벌칙 화면에서 오등록 정정을 먼저 처리해주세요.';
  end if;
  update rally.rsvps set attended=p_attended where event_id=p_event_id and user_id=p_uid and status='going';
  if not found then raise exception '참석 확정된 멤버만 기록할 수 있어요.'; end if;
end $$;
create or replace function public.rb_resolve_penalty(p_token text,p_id bigint,p_resolution text,p_note text) returns void language plpgsql security definer set search_path='' as $$
declare u rally.users := rally.require_admin(p_token); p rally.penalties;
begin
  perform pg_advisory_xact_lock(7281,1);
  select * into p from rally.penalties where id=p_id for update;
