CREATE OR REPLACE FUNCTION public.rb_signup(p_name text, p_yy text, p_region text, p_gender text, p_ntrp numeric, p_freq text, p_somoim text, p_pin text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_name text := btrim(coalesce(p_name,'')); v_region text := btrim(coalesce(p_region,'')); v_nick text; v_id bigint; v_som date;
begin
  perform rally.check_profile(v_name, p_yy, v_region);
  if p_gender not in ('M','F') then raise exception '성별을 골라주세요.'; end if;
  if not rally.valid_ntrp(p_ntrp) then raise exception 'NTRP를 골라주세요.'; end if;
  if rally.freq_emoji(p_freq) = '' then raise exception '실외코트 활동 빈도를 골라주세요.'; end if;
  v_som := rally.parse_ym(p_somoim);
  if coalesce(p_pin,'') !~ '^[0-9]{4}$' then raise exception 'PIN은 숫자 4자리예요.'; end if;
  if exists (select 1 from rally.users where lower(name) = lower(v_name) and birth_yy = p_yy and lower(region) = lower(v_region) and gender = p_gender and banned_at is not null) then
    raise exception '탈퇴 처리된 정보예요. 운영진에게 문의해주세요.';
  end if;
  if exists (select 1 from rally.users where lower(name) = lower(v_name) and birth_yy = p_yy and lower(region) = lower(v_region) and gender = p_gender) then
    raise exception '같은 정보로 가입한 멤버가 있어요. 로그인해주세요.';
  end if;
  v_nick := rally.make_nick(v_name, p_yy, v_region, p_gender, p_ntrp, p_freq);
  insert into rally.users(nickname, name, birth_yy, region, pin_hash, gender, ntrp, freq, somoim_joined, somoim_day_known, is_admin, is_owner)
  values (v_nick, v_name, p_yy, v_region, extensions.crypt(p_pin, extensions.gen_salt('bf', 8)), p_gender, p_ntrp, p_freq, v_som, true,
          not exists (select 1 from rally.users), not exists (select 1 from rally.users))
  returning id into v_id;
  return rally.new_session(v_id);
end $function$
;

CREATE OR REPLACE FUNCTION public.rb_take_promotion_pushes(p_secret text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v jsonb;
begin
  perform rally.check_secret(p_secret);
  with taken as (
    update rally.promotions set notified = true
    where id in (select id from rally.promotions where not notified order by created_at limit 100 for update skip locked)
    returning event_id, user_id)
  select coalesce(jsonb_agg(jsonb_build_object(
    'title', rally.push_text('promo','title', jsonb_build_object('제목', e.title, '시간', to_char(e.start_time,'HH24:MI') || '~' || to_char(e.end_time,'HH24:MI'))),
