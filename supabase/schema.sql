CREATE OR REPLACE FUNCTION rally.last_active(p_uid bigint)
 RETURNS date
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select max(d) from (
    select e.date as d from rally.rsvps r join rally.events e on e.id = r.event_id
    where r.user_id = p_uid and r.status = 'going' and r.attended is not false and not e.deleted and ((e.date + e.start_time) at time zone 'Asia/Seoul') <= now()
    union all
    select e.date from rally.events e where e.host_id = p_uid and not e.deleted and ((e.date + e.start_time) at time zone 'Asia/Seoul') <= now()
  ) a
$function$
;

