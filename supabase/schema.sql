  if cur in ('paid','exempt') then return; end if;
  insert into rally.dues(user_id, month, status, payer_name, reported_at) values (u.id, m, 'reported', v, now())
  on conflict (user_id, month) do update set status = 'reported', payer_name = excluded.payer_name, reported_at = now();
end $function$
