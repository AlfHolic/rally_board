CREATE OR REPLACE FUNCTION public.rb_login(p_nickname text, p_pin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare u rally.users; v_fails int;
begin
  select * into u from rally.users where lower(nickname) = lower(btrim(coalesce(p_nickname,'')));
  if u.id is null then return jsonb_build_object('error', '닉네임 또는 PIN이 맞지 않아요.'); end if;
  if u.locked_until is not null and u.locked_until > now() then return jsonb_build_object('error', 'PIN을 여러 번 틀려서 10분간 잠겼어요.'); end if;
  if extensions.crypt(coalesce(p_pin,''), u.pin_hash) <> u.pin_hash then
    v_fails := u.failed_count + 1;
    if v_fails >= 5 then
      update rally.users set failed_count = 0, locked_until = now() + interval '10 minutes' where id = u.id;
      return jsonb_build_object('error', 'PIN을 5번 틀려서 10분간 잠겼어요.');
    end if;
    update rally.users set failed_count = v_fails where id = u.id;
    return jsonb_build_object('error', '닉네임 또는 PIN이 맞지 않아요.');
  end if;
  update rally.users set failed_count = 0, locked_until = null where id = u.id;
  return jsonb_build_object('token', rally.new_session(u.id));
end $function$
;

CREATE OR REPLACE FUNCTION public.rb_login2(p_id text, p_yy text, p_pin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := btrim(coalesce(p_id,'')); u rally.users; v_hit bigint; v_any boolean := false;
begin
  for u in select * from rally.users
           where (coalesce(p_yy,'') <> '' and lower(name) = lower(v_id) and birth_yy = p_yy) or lower(nickname) = lower(v_id) loop
    v_any := true;
    if u.banned_at is not null then continue; end if;
    if u.locked_until is not null and u.locked_until > now() then continue; end if;
    if extensions.crypt(coalesce(p_pin,''), u.pin_hash) = u.pin_hash then v_hit := u.id; exit; end if;
  end loop;
  if v_hit is not null then
    update rally.users set failed_count = 0, locked_until = null where id = v_hit;
    return jsonb_build_object('token', rally.new_session(v_hit));
  end if;
  if v_any then
    update rally.users set failed_count = case when failed_count + 1 >= 5 then 0 else failed_count + 1 end,
      locked_until = case when failed_count + 1 >= 5 then now() + interval '10 minutes' else locked_until end
    where ((coalesce(p_yy,'') <> '' and lower(name) = lower(v_id) and birth_yy = p_yy) or lower(nickname) = lower(v_id)) and banned_at is null;
    if exists (select 1 from rally.users where ((coalesce(p_yy,'') <> '' and lower(name) = lower(v_id) and birth_yy = p_yy) or lower(nickname) = lower(v_id)) and banned_at is not null)
       and not exists (select 1 from rally.users where ((coalesce(p_yy,'') <> '' and lower(name) = lower(v_id) and birth_yy = p_yy) or lower(nickname) = lower(v_id)) and banned_at is null) then
      return jsonb_build_object('error', '탈퇴 처리된 계정이에요. 운영진에게 문의해주세요.');
    end if;
  end if;
  return jsonb_build_object('error', '이름·출생연도·PIN을 다시 확인해주세요. 5번 틀리면 10분간 잠겨요.');
