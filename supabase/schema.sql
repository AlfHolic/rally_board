CREATE OR REPLACE FUNCTION public.rb_update_event(p_token text, p_id bigint, p jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare u rally.users := rally.require_user(p_token); d jsonb := rally.norm_event(p); pay jsonb := rally.norm_pay(p); ev rally.events;
begin
