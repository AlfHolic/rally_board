CREATE OR REPLACE FUNCTION rally.norm_event(p jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  v_court text := btrim(coalesce(p->>'court',''));
  v_title text := btrim(coalesce(p->>'title',''));
  v_date date; v_start time; v_end time;
  v_type text := coalesce(p->>'gameType','any');
  v_cap int := coalesce((p->>'capacity')::int, 4);
  v_m int := coalesce((p->>'maleCap')::int, 0);
  v_f int := coalesce((p->>'femaleCap')::int, 0);
  v_min numeric := nullif(p->>'ntrpMin','')::numeric;
  v_max numeric := nullif(p->>'ntrpMax','')::numeric;
  v_cancel int := coalesce((p->>'cancelHours')::int, 0);
  v_note text := coalesce(p->>'note','');
  v_cf int := coalesce((p->>'courtFee')::int, 0);
  v_bf int := coalesce((p->>'ballFee')::int, 0);
begin
  begin
    v_date := (p->>'date')::date; v_start := (p->>'startTime')::time; v_end := (p->>'endTime')::time;
  exception when others then raise exception '날짜와 시간을 확인해주세요.';
  end;
  if v_date is null or v_start is null or v_end is null then raise exception '날짜와 시간을 확인해주세요.'; end if;
  if v_court = '' then raise exception '코트를 입력해주세요.'; end if;
  if length(v_court) > 40 or length(v_title) > 60 or length(v_note) > 300 then raise exception '입력한 글이 너무 길어요.'; end if;
  if v_end <= v_start then raise exception '끝나는 시간이 시작보다 늦어야 해요.'; end if;
  if v_type not in ('any','mens','womens','mixed') then raise exception '게임 유형을 확인해주세요.'; end if;
  if v_type = 'mixed' then
    if v_m < 0 or v_f < 0 or v_m > 20 or v_f > 20 or v_m + v_f = 0 then raise exception '혼복은 남녀 정원을 정해주세요.'; end if;
    v_cap := v_m + v_f;
  else
    if v_cap < 1 or v_cap > 40 then raise exception '정원은 1~40명이에요.'; end if;
    v_m := 0; v_f := 0;
  end if;
  if (v_min is not null and not rally.valid_ntrp(v_min)) or (v_max is not null and not rally.valid_ntrp(v_max)) or (v_min is not null and v_max is not null and v_min > v_max) then
    raise exception 'NTRP 범위를 확인해주세요.';
  end if;
  if v_cancel < 0 or v_cancel > 168 then raise exception '취소 마감을 확인해주세요.'; end if;
  if v_cf < 0 or v_bf < 0 or v_cf > 10000000 or v_bf > 10000000 then raise exception '비용을 확인해주세요.'; end if;
  if v_title = '' then
    v_title := extract(month from v_date)::int || '/' || extract(day from v_date)::int || ' ' || substr('일월화수목금토', extract(dow from v_date)::int + 1, 1) || ' ' || v_court;
  end if;
  return jsonb_build_object('title', v_title, 'court', v_court, 'date', v_date, 'start', v_start, 'end', v_end, 'type', v_type,
    'cap', v_cap, 'm', v_m, 'f', v_f, 'min', v_min, 'max', v_max, 'cancel', v_cancel, 'note', v_note, 'cf', v_cf, 'bf', v_bf);
end $function$
;

CREATE OR REPLACE FUNCTION rally.norm_pay(p jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO ''
AS $function$
declare l text := btrim(coalesce(p->>'payLink','')); a text := btrim(coalesce(p->>'account',''));
begin
  if l <> '' and (l !~* '^https://([a-z0-9-]+\.)*kakaopay\.com/' or length(l) > 300 or l ~ '\s') then
    raise exception '카카오페이 송금 링크를 확인해주세요. (https://qr.kakaopay.com/... 형태)';
  end if;
