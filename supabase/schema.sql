CREATE OR REPLACE FUNCTION rally.auth_user(p_token text)
 RETURNS rally.users
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select u.* from rally.sessions s join rally.users u on u.id = s.user_id
  where p_token is not null and s.token_hash = rally.hash_token(p_token) and s.expires_at > now() and u.banned_at is null
$function$
;

CREATE OR REPLACE FUNCTION rally.check_notice(p_title text, p_body text)
 RETURNS void
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO ''
AS $function$
begin
  if length(btrim(coalesce(p_title,''))) < 1 or length(p_title) > 80 then raise exception '제목은 1~80자예요.'; end if;
  if length(btrim(coalesce(p_body,''))) < 1 or length(p_body) > 3000 then raise exception '내용은 1~3000자예요.'; end if;
end $function$
;

CREATE OR REPLACE FUNCTION rally.check_profile(p_name text, p_yy text, p_region text)
 RETURNS void
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO ''
AS $function$
begin
  if p_name is null or length(p_name) < 1 or length(p_name) > 10 or position('/' in p_name) > 0 then raise exception '이름은 1~10자로 입력해주세요.'; end if;
  if coalesce(p_yy, '') !~ '^[0-9]{2}$' then raise exception '출생연도를 골라주세요.'; end if;
  if p_region is null or length(p_region) < 1 or length(p_region) > 12 or position('/' in p_region) > 0 then raise exception '지역(지하철역 또는 동)을 입력해주세요.'; end if;
end $function$
;

CREATE OR REPLACE FUNCTION rally.check_secret(p_secret text)
 RETURNS void
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$
begin
  if p_secret is null or p_secret <> (select secret from rally.server_secret where id = 1) then
    raise exception 'forbidden';
  end if;
end $function$
;

CREATE OR REPLACE FUNCTION rally.do_ban(p_uid bigint, p_reason text, p_kind text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  update rally.users set banned_at = now(), banned_reason = nullif(btrim(coalesce(p_reason,'')), ''), left_reason = p_kind, is_admin = false where id = p_uid;
  delete from rally.sessions where user_id = p_uid;
  delete from rally.push_subs where user_id = p_uid;
  perform rally.remove_from_upcoming(p_uid);
end $function$
;

