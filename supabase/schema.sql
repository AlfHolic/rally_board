CREATE OR REPLACE FUNCTION public.rb_cron_daily(p_secret text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare c jsonb := rally.dues_cfg(); v_today date := (now() at time zone 'Asia/Seoul')::date; m text := rally.kst_month();
  d int := extract(day from (now() at time zone 'Asia/Seoul'))::int; items jsonb := '[]'; u rally.users; n int; base date;
begin
  perform rally.check_secret(p_secret);
  begin
    insert into rally.cron_log values ('daily', v_today);
  exception when unique_violation then return '[]'::jsonb;
  end;
  if (c->>'amount')::int > 0 then
    if d = (c->>'startDay')::int then items := items || jsonb_build_array(rally.dues_item(m, 'dues')); end if;
    if (c->>'endDay')::int - 1 >= (c->>'startDay')::int and d = (c->>'endDay')::int - 1 then items := items || jsonb_build_array(rally.dues_item(m, 'dues_last')); end if;
  end if;
  for u in select * from rally.users x where x.banned_at is null and exists (select 1 from rally.push_subs s where s.user_id = x.id) loop
    base := rally.idle_base(u);
    n := v_today - base;
    if n >= 60 and not exists (select 1 from rally.nudges g where g.user_id = u.id and g.sent_for = base) then
      items := items || jsonb_build_array(jsonb_build_object(
        'title', rally.push_text('nudge','title', jsonb_build_object('이름', coalesce(u.name, u.nickname), '일수', n::text)),
        'body', rally.push_text('nudge','body', jsonb_build_object('이름', coalesce(u.name, u.nickname), '일수', n::text)),
        'url', '/', 'tag', 'nudge', 'subs', rally.subs_json(array[u.id])));
      insert into rally.nudges(user_id, sent_for) values (u.id, base) on conflict (user_id) do update set sent_for = excluded.sent_for, sent_at = now();
    end if;
  end loop;
  return items;
end $function$
;

