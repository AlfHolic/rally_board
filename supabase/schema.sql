CREATE OR REPLACE FUNCTION rally.dues_deadline(p_month text)
 RETURNS date
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select (p_month || '-01')::date + ((rally.dues_cfg()->>'endDay')::int - 1)
$function$
;

CREATE OR REPLACE FUNCTION rally.dues_item(p_month text, p_kind text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$
declare c jsonb := rally.dues_cfg(); v jsonb; dl date := rally.dues_deadline(p_month);
begin
  v := jsonb_build_object('월', extract(month from (p_month || '-01')::date)::int::text,
    '금액', to_char((c->>'amount')::int, 'FM999,999,999'), '마감일', extract(month from dl)::int || '/' || extract(day from dl)::int, '계좌', c->>'account');
  return jsonb_build_object('title', rally.push_text(p_kind,'title',v), 'body', rally.push_text(p_kind,'body',v), 'url', '/?dues=1', 'tag', 'dues-' || p_month,
    'subs', coalesce((select jsonb_agg(jsonb_build_object('endpoint', s.endpoint, 'p256dh', s.p256dh, 'auth', s.auth))
      from rally.push_subs s join rally.users u on u.id = s.user_id
      where rally.dues_required(u, p_month) and not exists (select 1 from rally.dues d where d.user_id = u.id and d.month = p_month)), '[]'::jsonb));
end $function$
;

CREATE OR REPLACE FUNCTION rally.dues_required(u rally.users, p_month text)
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select u.banned_at is null
    and (rally.dues_cfg()->>'amount')::int > 0
    and not (coalesce((rally.dues_cfg()->>'exemptAdmins')::boolean, false) and u.is_admin)
    and to_char(coalesce(u.somoim_joined, (u.created_at at time zone 'Asia/Seoul')::date), 'YYYY-MM') <= p_month
    and not (coalesce((rally.dues_cfg()->>'exemptJoinMonth')::boolean, true)
             and to_char(coalesce(u.somoim_joined, (u.created_at at time zone 'Asia/Seoul')::date), 'YYYY-MM') = p_month)
$function$
;

CREATE OR REPLACE FUNCTION rally.event_json(e rally.events, h rally.users, p_admin boolean)
 RETURNS jsonb
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select jsonb_build_object(
    'id', e.id, 'hostId', e.host_id, 'hostName', rally.shown_name(h), 'title', e.title, 'court', e.court,
    'date', to_char(e.date, 'YYYY-MM-DD'), 'startTime', to_char(e.start_time, 'HH24:MI'), 'endTime', to_char(e.end_time, 'HH24:MI'),
    'gameType', e.game_type, 'capacity', e.capacity, 'maleCap', e.male_cap, 'femaleCap', e.female_cap,
    'ntrpMin', e.ntrp_min, 'ntrpMax', e.ntrp_max, 'cancelHours', e.cancel_hours, 'note', e.note,
    'courtFee', e.court_fee, 'ballFee', e.ball_fee, 'payLink', e.pay_link, 'account', e.pay_account,
    'people', coalesce((
      select jsonb_agg(jsonb_build_object('id', u.id, 'nickname', case when p_admin then u.nickname else rally.shown_name(u) end, 'gender', u.gender, 'ntrp', u.ntrp, 'status', r.status, 'attended', r.attended) order by r.queued_at)
      from rally.rsvps r join rally.users u on u.id = r.user_id where r.event_id = e.id), '[]'::jsonb),
