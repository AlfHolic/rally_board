create table if not exists rally.payment_audit (
  id bigint generated by default as identity primary key, event_id bigint references rally.events(id), user_id bigint references rally.users(id),
  actor_id bigint references rally.users(id), action text not null, note text not null, created_at timestamptz not null default now()
);

create or replace function rally.event_fee(e rally.events) returns integer language sql immutable set search_path='' as $$
  select (ceil((e.court_fee + e.ball_fee)::numeric / greatest(e.capacity,1) / 100) * 100)::integer
$$;
create or replace function rally.attendance_blocked(p_uid bigint) returns boolean language sql stable set search_path='' as $$
  select exists(select 1 from rally.penalties where user_id=p_uid and blocks_attendance and status in ('unpaid','reported'))
$$;
create or replace function rally.eligible(e rally.events,u rally.users) returns boolean language sql stable set search_path='' as $$
  select u.banned_at is null and not rally.attendance_blocked(u.id)
    and (e.game_type <> 'mens' or u.gender='M') and (e.game_type <> 'womens' or u.gender='F')
    and (e.ntrp_min is null or u.ntrp >= e.ntrp_min) and (e.ntrp_max is null or u.ntrp <= e.ntrp_max)
$$;
create or replace function rally.has_seat(e rally.events,u rally.users) returns boolean language sql stable set search_path='' as $$
  select (select count(*) from rally.rsvps r join rally.users x on x.id=r.user_id
    where r.event_id=e.id and r.status='going' and r.user_id<>u.id and (e.game_type<>'mixed' or x.gender=u.gender))
    < case when e.game_type='mixed' then case when u.gender='M' then e.male_cap else e.female_cap end else e.capacity end
$$;
create or replace function rally.notify_event(p_eid bigint,p_uid bigint,p_title text,p_body text) returns void language sql set search_path='' as $$
  insert into rally.inbox(user_id,event_id,title,body)
  select id,p_eid,p_title,p_body from rally.users
  where banned_at is null and (id=p_uid or is_admin or id=(select host_id from rally.events where id=p_eid))
$$;
create or replace function rally.manage_event(p_token text,p_eid bigint) returns rally.users language plpgsql stable set search_path='' as $$
declare u rally.users := rally.require_user(p_token); e rally.events;
begin
  select * into e from rally.events where id=p_eid and not deleted;
  if e.id is null then raise exception '일정을 찾을 수 없어요.'; end if;
  if e.host_id<>u.id and not u.is_admin then raise exception '해당 호스트와 운영진만 관리할 수 있어요.'; end if;
  return u;
end $$;

-- Promotion rechecks eligibility and never confirms unpaid participation.
create or replace function rally.promote(p_eid bigint) returns void language plpgsql set search_path='' as $$
declare e rally.events; u rally.users; next_status text;
begin
  select * into e from rally.events where id=p_eid and not deleted for update;
  if e.id is null or ((e.date+e.start_time) at time zone 'Asia/Seoul') <= now() then return; end if;
  for u in select x.* from rally.rsvps r join rally.users x on x.id=r.user_id
    where r.event_id=p_eid and r.status='waiting' order by r.queued_at loop
    if not rally.eligible(e,u) or not rally.has_seat(e,u) then continue; end if;
    next_status := case when rally.event_fee(e)=0 or exists(select 1 from rally.event_payments p
      where p.event_id=p_eid and p.user_id=u.id and p.status='paid') then 'going' else 'payment_pending' end;
    update rally.rsvps set status=next_status where event_id=p_eid and user_id=u.id;
    if next_status='going' then insert into rally.promotions(event_id,user_id) values(p_eid,u.id); end if;
    perform rally.notify_event(p_eid,u.id,case when next_status='going' then '참석 확정' else '입금 확인 대기' end,
      e.title || case when next_status='going' then ' · 자리가 배정됐어요.' else ' · 입금 전 호스트에게 자리와 금액을 확인해주세요. 입금 대기는 자리 확정이 아니에요.' end);
  end loop;
end $$;

