CREATE OR REPLACE FUNCTION rally.promote(p_eid bigint)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare ev rally.events; g text; v_open int;
begin
  select * into ev from rally.events where id = p_eid for update;
  if ev.id is null then return; end if;
  foreach g in array (case when ev.game_type = 'mixed' then array['M','F'] else array['*'] end) loop
    select (case when g = 'M' then ev.male_cap when g = 'F' then ev.female_cap else ev.capacity end)
           - count(*) into v_open
    from rally.rsvps r join rally.users u on u.id = r.user_id
    where r.event_id = p_eid and r.status = 'going' and (g = '*' or u.gender = g);
    if v_open > 0 then
      with up as (
        update rally.rsvps set status = 'going'
        where event_id = p_eid and user_id in (
          select r.user_id from rally.rsvps r join rally.users u on u.id = r.user_id
          where r.event_id = p_eid and r.status = 'waiting' and (g = '*' or u.gender = g)
          order by r.queued_at limit v_open)
        returning user_id)
      insert into rally.promotions(event_id, user_id) select p_eid, user_id from up;
    end if;
  end loop;
end $function$
;

